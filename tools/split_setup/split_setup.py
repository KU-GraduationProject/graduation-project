"""분리 구성(Leafy 장비 <-> AIOps 장비) 설정 파일 생성 (#62). 표준 라이브러리만 쓴다 (macOS·Windows 공통).

두 장비에서 같은 값을 쓰도록 Leafy 장비의 docker inspect 결과 하나에서 모든 파일을 만든다.

  leafy : Leafy 장비에서 실행. workload 라벨이 붙은 컨테이너를 docker inspect로 읽어 만든다.
          - <agent-dir>/allowlist.yml               Remediation Agent 허용 목록
          - <agent-dir>/secrets/agent_hmac_key.txt  HMAC 키 (없을 때만 만든다. 값은 출력하지 않는다)
          - <out>/leafy.env                         Leafy compose .env에 넣을 값
          - <out>/telemetry-config.json             지표 collector 설정 (compose.remote.yml)
          - <out>/aiops-bundle.json                 AIOps 장비로 넘길 값 (비밀값 없음)
  aiops : AIOps 장비에서 실행. aiops-bundle.json과 HMAC 키 사본으로 만든다.
          - <out>/remediation_targets.yml           Remediation 원격 대상 바인딩 (executor: remote)
          - <out>/leafy-telemetry.yml               Prometheus 대상 파일 (monitoring/prometheus/targets/로 복사)
          - <out>/aiops.env                         AIOps .env에 넣을 값 (OBSERVATION_BINDINGS 등)

YAML 파일은 JSON 형식으로 쓴다 (JSON은 YAML의 부분집합이라 그대로 읽힌다).
절차는 docs/remote/SPLIT_E2E_RUNBOOK.md.
"""
import argparse
import ipaddress
import json
import os
import re
import secrets
import subprocess
import sys
from pathlib import Path
from urllib.parse import urlsplit

REPO = Path(__file__).resolve().parents[2]
NAME = re.compile(r"[A-Za-z0-9][A-Za-z0-9_.-]{0,127}\Z")
ID = re.compile(r"[A-Za-z0-9_-]{1,64}\Z")
CID = re.compile(r"[a-f0-9]{64}\Z")
IMAGE = re.compile(r"sha256:[a-f0-9]{64}\Z")
SERVICES = ("backend", "frontend", "minio")
DEFAULT_CONTAINERS = {"backend": "leafy-backend", "frontend": "leafy-frontend", "minio": "leafy-minio"}
TELEMETRY_JOB = "leafy-telemetry"
TELEMETRY_PORT = 9108
HEADER = "# generated by tools/split_setup.py (#62). 직접 고치지 말고 스크립트를 다시 실행한다.\n"


class SetupError(ValueError):
    pass


def docker_inspect(name):
    result = subprocess.run(["docker", "inspect", name], capture_output=True, text=True)
    if result.returncode != 0:
        raise SetupError(f"docker inspect {name} 실패: 컨테이너가 있는지 확인한다")
    return json.loads(result.stdout)[0]


def matches(network, patterns):
    """Remediation 실행기와 같은 규칙: compose 접두사가 붙은 이름도 맞춘다."""
    name = network.lower()
    return any(name == p.lower() or name.endswith("_" + p.lower()) or name.endswith("-" + p.lower())
               for p in patterns if p)


def check_name(value, what, pattern=NAME):
    if not isinstance(value, str) or not pattern.fullmatch(value):
        raise SetupError(f"{what} 형식이 잘못됐다: {value!r}")
    return value


def check_ip(value, what):
    try:
        return str(ipaddress.IPv4Address(value))
    except ValueError:
        raise SetupError(f"{what}는 IPv4 주소여야 한다 (tailscale ip -4): {value!r}") from None


def check_agent_url(value):
    url = urlsplit(value)
    if (url.scheme != "https" or not url.hostname or not url.hostname.endswith(".ts.net")
            or url.username or url.password or url.query or url.fragment or url.path not in ("", "/")):
        raise SetupError("agent-url은 Tailscale Serve 주소여야 한다: https://<장비>.<tailnet>.ts.net")
    return value.rstrip("/")


def target_from_inspect(info, service, name, site, isolate, preserve):
    labels = (info.get("Config") or {}).get("Labels") or {}
    if labels.get("io.leafy.remediation") != "workload":
        raise SetupError(f"{name}: io.leafy.remediation=workload 라벨이 없다. "
                         "leafy-compose-logging.example.yml을 적용하고 컨테이너를 다시 만든다")
    if labels.get("aiops.site") != site:
        raise SetupError(f"{name}: aiops.site 라벨({labels.get('aiops.site')!r})이 site({site!r})와 다르다. "
                         ".env의 LEAFY_SITE를 맞추고 컨테이너를 다시 만든다")
    if labels.get("com.docker.compose.service") != service:
        raise SetupError(f"{name}: compose 서비스가 {service}가 아니다")
    if not labels.get("com.docker.compose.project"):
        raise SetupError(f"{name}: compose 프로젝트 라벨이 없다")
    if info.get("Name", "").lstrip("/") != name or not (info.get("State") or {}).get("Running"):
        raise SetupError(f"{name}: 실행 중인 컨테이너가 아니다")
    cid, image = info.get("Id", ""), info.get("Image", "")
    if not CID.fullmatch(cid) or not IMAGE.fullmatch(image):
        raise SetupError(f"{name}: 컨테이너/이미지 id 형식이 예상과 다르다")
    actions = ["RESTART", "PAUSE", "UNPAUSE"]
    # NanoCPUs(--cpus)로 제한된 컨테이너는 Agent가 THROTTLE을 거부한다.
    if not (info.get("HostConfig") or {}).get("NanoCpus"):
        actions += ["THROTTLE", "UNTHROTTLE"]
    networks = sorted(((info.get("NetworkSettings") or {}).get("Networks") or {}))
    isolate_networks, preserve_networks = [], []
    # ISOLATE는 끊을 네트워크와 남길 관리 네트워크가 둘 다 붙어 있을 때만 허용한다.
    if (isolate and preserve and any(matches(n, isolate) for n in networks)
            and any(matches(n, preserve) for n in networks)):
        actions += ["ISOLATE", "RECONNECT"]
        isolate_networks, preserve_networks = list(isolate), list(preserve)
    return {
        "service": service, "name": name, "container_id": cid, "image_id": image,
        "labels": {"io.leafy.remediation": "workload",
                   "com.docker.compose.project": labels["com.docker.compose.project"],
                   "com.docker.compose.service": service},
        "actions": actions, "isolate_networks": isolate_networks, "preserve_networks": preserve_networks,
        "networks": networks,
    }


def build_bundle(args, inspect=docker_inspect):
    site = check_name(args.site, "site")
    source = check_name(args.source or f"{site}-docker", "source")
    agent_id = check_name(args.agent_id or f"{site}-agent", "agent-id", ID)
    controller_id = check_name(args.controller_id, "controller-id", ID)
    containers = dict(DEFAULT_CONTAINERS)
    for item in args.container or ():
        service, _, name = item.partition("=")
        if service not in SERVICES:
            raise SetupError(f"--container 서비스는 {', '.join(SERVICES)} 중 하나다: {item!r}")
        containers[service] = check_name(name, f"{service} 컨테이너 이름")
    targets = [target_from_inspect(inspect(name), service, name, site, args.isolate_network or [],
                                   args.preserve_network or [])
               for service, name in sorted(containers.items())]
    projects = {t["labels"]["com.docker.compose.project"] for t in targets}
    if len(projects) != 1:
        raise SetupError(f"컨테이너들의 compose 프로젝트가 하나가 아니다: {sorted(projects)}")
    return {"version": 1, "site": site, "source": source, "project": projects.pop(),
            "aiops_ip": check_ip(args.aiops_ip, "aiops-ip"), "leafy_ip": check_ip(args.leafy_ip, "leafy-ip"),
            "agent_url": check_agent_url(args.agent_url), "agent_id": agent_id,
            "controller_id": controller_id, "targets": targets}


def allowlist(bundle):
    return {"controller_id": bundle["controller_id"], "agent_id": bundle["agent_id"],
            "site": bundle["site"], "source": bundle["source"],
            "targets": {t["name"]: {k: t[k] for k in ("container_id", "image_id", "labels", "actions",
                                                      "isolate_networks", "preserve_networks")}
                        for t in bundle["targets"]}}


def telemetry_config(bundle):
    return {"site": bundle["site"], "source": bundle["source"], "project": bundle["project"],
            "targets": {t["service"]: t["name"] for t in bundle["targets"]}}


def identity(bundle, target):
    return {"site": bundle["site"], "service": target["service"], "runtime": "container",
            "target": target["name"], "source": bundle["source"]}


def observation_bindings(bundle):
    rows = []
    for t in bundle["targets"]:
        ident = identity(bundle, t)
        rows.append({
            "identity": ident,
            "match": {"site": bundle["site"], "target": t["name"]},
            "logs": {"site": bundle["site"], "service": t["service"], "runtime": "container",
                     "container_name": t["name"]},
            "metrics": {"job": TELEMETRY_JOB, "instance": f"{bundle['leafy_ip']}:{TELEMETRY_PORT}",
                        "id": "/docker/" + t["container_id"], **ident},
            "metrics_profile": "gc-telemetry-v1",
        })
    return rows


def target_bindings(bundle):
    return {"version": 1, "bindings": [
        {"identity": identity(bundle, t), "executor": "remote", "agent_id": bundle["agent_id"],
         "agent_url": bundle["agent_url"],
         "container": {k: t[k] for k in ("container_id", "image_id", "labels", "actions",
                                         "isolate_networks", "preserve_networks")}}
        for t in bundle["targets"]]}


def write(path, text, force=True):
    path = Path(path)
    if path.exists() and not force:
        raise SetupError(f"{path} 가 이미 있다. 덮어쓰려면 --force")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


def as_yaml(data):
    return HEADER + json.dumps(data, ensure_ascii=False, indent=2) + "\n"


def env_lines(values):
    return HEADER + "".join(f"{k}={v}\n" for k, v in values.items())


def ensure_key(path):
    """32바이트 난수(hex 64자). 이미 있으면 그대로 둔다 (Agent·AIOps 양쪽 키가 어긋나지 않게)."""
    path = Path(path)
    if path.exists():
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(secrets.token_hex(32))
    return True


def run_leafy(args, inspect=docker_inspect):
    bundle = build_bundle(args, inspect)
    out = Path(args.out or f"split-setup/{bundle['site']}/leafy")
    agent_dir = Path(args.agent_dir)
    written = [
        write(agent_dir / "allowlist.yml", as_yaml(allowlist(bundle)), force=args.force),
        write(out / "telemetry-config.json", json.dumps(telemetry_config(bundle), indent=2) + "\n"),
        write(out / "leafy.env", env_lines({"AIOPS_TAILSCALE_IP": bundle["aiops_ip"], "LEAFY_SITE": bundle["site"],
                                            "LEAFY_TAILSCALE_IP": bundle["leafy_ip"]})),
        write(out / "aiops-bundle.json", json.dumps(bundle, ensure_ascii=False, indent=2) + "\n"),
    ]
    key = agent_dir / "secrets" / "agent_hmac_key.txt"
    created = ensure_key(key)
    return written, key, created, bundle


def run_aiops(args):
    bundle = json.loads(Path(args.bundle).read_text(encoding="utf-8"))
    if bundle.get("version") != 1:
        raise SetupError("aiops-bundle.json 버전이 다르다")
    key = Path(args.hmac_key_file).resolve()
    if len(key.read_text(encoding="utf-8").strip()) < 32:
        raise SetupError("HMAC 키가 32자보다 짧다. Leafy 장비의 agent_hmac_key.txt 사본을 쓴다")
    bundle["aiops_ip"] = check_ip(args.aiops_ip, "aiops-ip")
    out = Path(args.out or f"split-setup/{bundle['site']}/aiops")
    targets_path = write(out / "remediation_targets.yml", as_yaml(target_bindings(bundle)))
    written = [
        targets_path,
        write(out / "leafy-telemetry.yml", as_yaml([{"targets": [f"{bundle['leafy_ip']}:{TELEMETRY_PORT}"],
                                                     "labels": {"site": bundle["site"]}}])),
        write(out / "aiops.env", env_lines({
            "AIOPS_TAILSCALE_IP": bundle["aiops_ip"],
            "OBSERVATION_BINDINGS": "'" + json.dumps(observation_bindings(bundle), separators=(",", ":")) + "'",
            "REMEDIATION_TARGET_BINDINGS_LOCAL_PATH": str(targets_path.resolve()),
            "REMEDIATION_AGENT_URL": bundle["agent_url"],
            "AGENT_HMAC_KEY_LOCAL_PATH": str(key),
        })),
    ]
    return written, bundle


def parser():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="role", required=True)
    leafy = sub.add_parser("leafy", help="Leafy 장비: docker inspect로 허용 목록·키·번들 생성")
    leafy.add_argument("--site", required=True, help="이 장비 이름 = LEAFY_SITE (예: gc-mac)")
    leafy.add_argument("--aiops-ip", required=True, help="AIOps 장비 tailscale ip -4")
    leafy.add_argument("--leafy-ip", required=True, help="이 장비 tailscale ip -4")
    leafy.add_argument("--agent-url", required=True, help="이 장비 Tailscale Serve 주소 https://<장비>.<tailnet>.ts.net")
    leafy.add_argument("--source", help="기본 <site>-docker")
    leafy.add_argument("--agent-id", help="기본 <site>-agent")
    leafy.add_argument("--controller-id", default="pc1")
    leafy.add_argument("--container", action="append", metavar="SERVICE=NAME",
                       help="기본 backend=leafy-backend frontend=leafy-frontend minio=leafy-minio")
    leafy.add_argument("--isolate-network", action="append", metavar="NAME", help="ISOLATE가 끊을 업무 네트워크")
    leafy.add_argument("--preserve-network", action="append", metavar="NAME", help="ISOLATE 중에도 남길 관리 네트워크")
    leafy.add_argument("--agent-dir", default=str(REPO / "deploy/leafy-pc/remediation-agent"))
    leafy.add_argument("--out", help="기본 split-setup/<site>/leafy")
    leafy.add_argument("--force", action="store_true", help="기존 allowlist.yml 덮어쓰기")
    aiops = sub.add_parser("aiops", help="AIOps 장비: 번들로 대상 바인딩·Prometheus 대상·.env 값 생성")
    aiops.add_argument("--bundle", required=True, help="Leafy 장비에서 만든 aiops-bundle.json")
    aiops.add_argument("--aiops-ip", required=True, help="이 장비 tailscale ip -4")
    aiops.add_argument("--hmac-key-file", required=True, help="Leafy 장비 agent_hmac_key.txt를 안전하게 옮긴 사본")
    aiops.add_argument("--out", help="기본 split-setup/<site>/aiops")
    return p


def main(argv=None):
    args = parser().parse_args(argv)
    try:
        if args.role == "leafy":
            written, key, created, bundle = run_leafy(args)
            print("\n".join(f"생성: {p}" for p in written))
            print(f"HMAC 키: {key} ({'새로 생성' if created else '기존 키 유지'}). 값은 출력하지 않는다.")
            if created and os.name == "nt":
                print('  Windows: icacls "' + str(key.parent) + '" /inheritance:r /grant:r "%USERNAME%:(OI)(CI)F"')
            skipped = [t["name"] for t in bundle["targets"] if "ISOLATE" not in t["actions"]]
            if skipped:
                print(f"ISOLATE 미허용: {', '.join(skipped)} (--isolate-network/--preserve-network와 붙은 네트워크 확인)")
            print("다음: aiops-bundle.json과 HMAC 키 사본을 AIOps 장비로 옮겨 `split_setup.py aiops`를 실행한다.")
        else:
            written, _ = run_aiops(args)
            print("\n".join(f"생성: {p}" for p in written))
            print("다음: aiops.env 값을 .env에 넣고 leafy-telemetry.yml을 monitoring/prometheus/targets/로 복사한다.")
    except (SetupError, OSError, json.JSONDecodeError) as e:
        print(f"오류: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
